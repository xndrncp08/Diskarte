import { DEFAULT_PUSH_PREFS, notificationsQuiet, parseNotifyPrefs, serverNotify, type PushKind } from "./notify-prefs";
export function allowPush(raw: unknown, kind: PushKind | "test", serverId: string | null, channelId: string | null, now = new Date()) {
  const prefs = parseNotifyPrefs(JSON.stringify(raw));
  const push = prefs.push ?? DEFAULT_PUSH_PREFS;
  if (!push.enabled || notificationsQuiet(prefs, now)) return false;
  if (kind !== "test" && !push.events[kind] || kind === "dm" && !prefs.dms) return false;
  if (serverId && (serverNotify(prefs, serverId, now.getTime()).muted || serverNotify(prefs, serverId, now.getTime()).level === "nothing")) return false;
  const channel = channelId ? prefs.channels?.[channelId] : undefined;
  if (channel?.muted && (channel.muteUntil === undefined || channel.muteUntil > now.getTime())) return false;
  return true;
}
/** Vendor allow-list, no credentials/ports/fragments/redirects or arbitrary HTTPS destinations. */
export function validPushEndpoint(value: string) {
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password && !url.port && !url.hash && url.pathname.length > 1 &&
      /^(fcm\.googleapis\.com|updates\.push\.services\.mozilla\.com|[a-z0-9-]+\.notify\.windows\.com|[a-z0-9-]+\.push\.apple\.com|web\.push\.apple\.com)$/.test(url.hostname);
  } catch { return false; }
}
/** Notification targets are generated by the server; still validate again at the browser boundary. */
export function safePushPath(path: unknown) {
  return typeof path === "string" && /^\/(tambayan|settings)(\/|\?|$)/.test(path) && !/[\\\r\n]/.test(path) ? path : "/tambayan";
}
