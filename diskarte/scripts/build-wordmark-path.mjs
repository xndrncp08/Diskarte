// Converts the "Diskarte" wordmark into pure SVG path data using the
// Knewave brush typeface (SIL OFL, see assets/fonts/OFL-Knewave.txt).
// The output is committed so the UI never depends on a web font for the logo.
//
// Usage: node scripts/build-wordmark-path.mjs
import fs from "node:fs";
import path from "node:path";
import opentype from "opentype.js";

const root = path.resolve(import.meta.dirname, "..");
const fontFile = fs.readFileSync(path.join(root, "assets/fonts/Knewave-Regular.ttf"));
const font = opentype.parse(fontFile.buffer.slice(fontFile.byteOffset, fontFile.byteOffset + fontFile.byteLength));

const FONT_SIZE = 200;
const DOTLESS_I = "ı";
const hasDotless = font.charToGlyphIndex(DOTLESS_I) > 0;
const text = hasDotless ? `D${DOTLESS_I}skarte` : "Diskarte";

const glyphs = font.stringToGlyphs(text);
const scale = FONT_SIZE / font.unitsPerEm;
let x = 0;
const parts = [];
let iBox = null;
glyphs.forEach((glyph, index) => {
  const glyphPath = glyph.getPath(x, 0, FONT_SIZE);
  parts.push(glyphPath);
  if (index === 1 && !hasDotless) {
    // Split the "i" into contours and drop the tittle (topmost contour) so it can be redrawn in gold.
    const contours = [];
    let current = [];
    for (const cmd of glyphPath.commands) {
      if (cmd.type === "M" && current.length) {
        contours.push(current);
        current = [];
      }
      current.push(cmd);
    }
    if (current.length) contours.push(current);
    const boxed = contours.map((cmds) => {
      const p = new opentype.Path();
      p.commands = cmds;
      return { cmds, box: p.getBoundingBox() };
    });
    boxed.sort((a, b) => a.box.y1 - b.box.y1);
    const [tittle, ...rest] = boxed;
    iBox = tittle.box;
    glyphPath.commands = rest.flatMap((c) => c.cmds);
  } else if (index === 1) {
    iBox = glyphPath.getBoundingBox();
  }
  const next = glyphs[index + 1];
  const kerning = next ? font.getKerningValue(glyph, next) : 0;
  x += (glyph.advanceWidth + kerning) * scale;
});

const all = new opentype.Path();
parts.forEach((p) => all.extend(p));
const box = all.getBoundingBox();
const pad = 4;
const round = (n) => Math.round(n * 10) / 10;
const translate = (p) => {
  p.commands.forEach((c) => {
    for (const key of ["x", "y", "x1", "y1", "x2", "y2"]) {
      if (key in c) c[key] = key.startsWith("x") ? c[key] - box.x1 + pad : c[key] - box.y1 + pad;
    }
  });
  return p;
};
translate(all);

const width = round(box.x2 - box.x1 + pad * 2);
const height = round(box.y2 - box.y1 + pad * 2);
const dot = iBox
  ? {
      cx: round((iBox.x1 + iBox.x2) / 2 - box.x1 + pad),
      cy: round((iBox.y1 + iBox.y2) / 2 - box.y1 + pad),
      r: round(Math.max(iBox.x2 - iBox.x1, iBox.y2 - iBox.y1) * 0.55),
    }
  : null;

// opentype's toPathData(decimals) emits "NaN" for values like 121.00000000000001, so serialize by hand.
const fmt = (n) => String(round(n));
const pathData = all.commands
  .map((c) => {
    switch (c.type) {
      case "M":
      case "L":
        return `${c.type}${fmt(c.x)} ${fmt(c.y)}`;
      case "Q":
        return `Q${fmt(c.x1)} ${fmt(c.y1)} ${fmt(c.x)} ${fmt(c.y)}`;
      case "C":
        return `C${fmt(c.x1)} ${fmt(c.y1)} ${fmt(c.x2)} ${fmt(c.y2)} ${fmt(c.x)} ${fmt(c.y)}`;
      default:
        return "Z";
    }
  })
  .join("");
if (pathData.includes("NaN")) throw new Error("Wordmark path contains NaN");

const out = `// AUTO-GENERATED by scripts/build-wordmark-path.mjs — do not edit by hand.
// Glyph outlines: Knewave by Tyler Finck (SIL Open Font License 1.1).

export const WORDMARK_TEXT_PATH =
  ${JSON.stringify(pathData)};

export const WORDMARK_TEXT_BOX = { width: ${width}, height: ${height} } as const;

/** Position of the golden tittle drawn over the "i" (its original dot is removed from the path). */
export const WORDMARK_I_DOT: { cx: number; cy: number; r: number } = ${JSON.stringify(dot)};
`;
fs.writeFileSync(path.join(root, "src/components/brand/wordmark-path.ts"), out);
console.log({ text, hasDotless, width, height, dot, bytes: out.length });
